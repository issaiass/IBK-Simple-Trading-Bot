"""Morning prefilter: gap-up screen of the S&P 500 using 2-day Yahoo bars.

Yahoo does the screening (no concurrent-request cap, unlike IBKR market data);
IBKR still handles execution.
"""
import argparse
import json
import sys
import time
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import pandas as pd
import yfinance as yf

from trading_bot.config import WATCHLIST_PATH
from trading_bot.notify import notify as default_notify
from trading_bot.notify import send_safely
from trading_bot.scanner.gappers import to_yahoo
from trading_bot.sp500_tickers import SP500_TICKERS
from trading_bot.timeutil import now_et

DEFAULT_MIN_GAP_PCT = 3.0
DEFAULT_MIN_PRICE = 3.0
MAX_SURVIVORS = 20
DOWNLOAD_THREADS = 5  # higher concurrency exhausts file descriptors under Task Scheduler
DEGRADED_RATIO = 0.30
WIDE_FAILURE_RATIO = 0.95


class PrefilterError(Exception):
    """The run cannot produce a result (e.g. Yahoo returned nothing)."""


@dataclass(frozen=True)
class Candidate:
    symbol: str
    gap_pct: float
    open: float
    high: float
    low: float
    close: float
    prev_close: float


@dataclass
class ScreenResult:
    survivors: list[Candidate] = field(default_factory=list)  # sorted, capped
    below_gap: list[str] = field(default_factory=list)
    below_price: list[str] = field(default_factory=list)
    failed: list[str] = field(default_factory=list)


def _candidate(symbol: str, bars: pd.DataFrame | None) -> Candidate:
    """Build a candidate from [yesterday, today] bars; raises on unusable data."""
    if bars is None:
        raise ValueError("no data")
    yesterday, today = bars.iloc[-2], bars.iloc[-1]
    prev_close, close = float(yesterday["Close"]), float(today["Close"])
    open_, high, low = float(today["Open"]), float(today["High"]), float(today["Low"])
    if any(pd.isna(v) for v in (prev_close, close, open_, high, low)):
        raise ValueError("NaN in bars")
    if prev_close <= 0:
        raise ValueError("non-positive prior close")
    gap = (close - prev_close) / prev_close * 100
    return Candidate(symbol, gap, open_, high, low, close, prev_close)


def screen(
    frames: Mapping[str, pd.DataFrame | None], min_gap: float, min_price: float
) -> ScreenResult:
    """Classify every symbol; unusable data is recorded, never raised."""
    result = ScreenResult()
    passed: list[Candidate] = []
    for symbol, bars in frames.items():
        try:
            c = _candidate(symbol, bars)
        except (KeyError, IndexError, ValueError, TypeError):
            result.failed.append(symbol)
            continue
        if c.close < min_price:
            result.below_price.append(symbol)
        elif c.gap_pct < min_gap:
            result.below_gap.append(symbol)
        else:
            passed.append(c)
    passed.sort(key=lambda c: c.gap_pct, reverse=True)
    result.survivors = passed[:MAX_SURVIVORS]
    return result


def tripwire_alerts(failed: int, total: int) -> list[str]:
    if total == 0:
        return []
    ratio = failed / total
    if ratio >= WIDE_FAILURE_RATIO:
        return ["ALERT: Yahoo-wide failure suspected; check yfinance changelog"]
    if ratio >= DEGRADED_RATIO:
        return [f"ALERT: yfinance degradation (failed {failed}/{total})"]
    return []


def format_watchlist(
    survivors: list[Candidate], min_gap: float, min_price: float, total: int, now: datetime
) -> str:
    lines = [
        f"# Auto-generated by morning_prefilter.py at {now:%Y-%m-%d %H:%M} {now.tzname()}",
        f"# Filters: gap >= {min_gap}%, price >= ${min_price}",
        "# Source: yfinance (screening only); IBKR handles execution",
        f"# Survivors: {len(survivors)} (capped at {MAX_SURVIVORS}) of {total}",
        "#",
        "# ticker  # gap +X.XX%  open $X.XX  prev $X.XX",
    ]
    lines += [
        f"{c.symbol}  # gap {c.gap_pct:+.2f}%  open ${c.open:.2f}  prev ${c.prev_close:.2f}"
        for c in survivors
    ]
    return "\n".join(lines) + "\n"


def download_daily(symbols: list[str]) -> dict[str, pd.DataFrame | None]:
    """2 daily bars per symbol; symbols Yahoo returned nothing for map to None."""
    data = yf.download(
        tickers=" ".join(to_yahoo(s) for s in symbols),
        period="2d",
        interval="1d",
        group_by="ticker",
        threads=DOWNLOAD_THREADS,
        progress=False,
        auto_adjust=True,
    )
    if data.empty:
        raise PrefilterError("yf.download returned an empty dataframe")
    frames: dict[str, pd.DataFrame | None] = {}
    for symbol in symbols:
        try:
            frames[symbol] = data[to_yahoo(symbol)].dropna(how="all")
        except KeyError:
            frames[symbol] = None
    return frames


def _latest_bar_date(frames: Mapping[str, pd.DataFrame | None]):
    dates = [f.index[-1].date() for f in frames.values() if f is not None and len(f)]
    return max(dates) if dates else None


def run(
    symbols: list[str],
    min_gap: float,
    min_price: float,
    dry_run: bool,
    download: Callable[[list[str]], Mapping[str, pd.DataFrame | None]] = download_daily,
    *,
    now: datetime | None = None,
    watchlist_path: Path = WATCHLIST_PATH,
    out: Callable[[str], None] = print,
    err: Callable[[str], None] = lambda m: print(m, file=sys.stderr),
    notify: Callable[[str, str, str], None] = default_notify,
) -> int:
    """Screen, optionally write watchlist.txt, print the JSON summary.

    Unless `dry_run`, also pushes a notification (summary, failure or tripwire).
    """
    started = time.monotonic()
    now = now or now_et()
    clock = f"{now:%H:%M} ET"

    def push(title: str, body: str, priority: str = "default") -> None:
        if not dry_run:
            send_safely(notify, title, body, priority)

    try:
        frames = download(symbols)
    except PrefilterError as exc:
        out(json.dumps({"success": False, "error": str(exc)}))
        push(f"Prefilter FAILED {clock}", str(exc), "high")
        return 1

    result = screen(frames, min_gap, min_price)
    for alert in tripwire_alerts(len(result.failed), len(symbols)):
        err(alert)
        push(f"Prefilter ALERT {clock}", alert, "high")
    latest = _latest_bar_date(frames)
    if latest is not None and latest != now.date():
        err(f"WARNING: latest bar is {latest}, not today ({now.date()}); gaps are stale")

    if not dry_run:
        temp = watchlist_path.with_suffix(watchlist_path.suffix + ".tmp")
        temp.write_text(
            format_watchlist(result.survivors, min_gap, min_price, len(symbols), now),
            encoding="utf-8",
        )
        temp.replace(watchlist_path)

    elapsed = round(time.monotonic() - started, 2)
    out(json.dumps({
        "success": True,
        "total_screened": len(symbols),
        "survivors_count": len(result.survivors),
        "below_gap": len(result.below_gap),
        "below_price": len(result.below_price),
        "failed": len(result.failed),
        "elapsed_seconds": elapsed,
        "top_20_survivors": [f"{c.symbol} ({c.gap_pct:+.2f}%)" for c in result.survivors],
        "watchlist_path": None if dry_run else str(watchlist_path),
    }))
    bullets = [f"• {c.symbol} {c.gap_pct:+.2f}%" for c in result.survivors]
    header = f"{len(result.survivors)}/{len(symbols)} survivors in {elapsed}s"
    push(f"Prefilter {clock}", "\n".join([header, *bullets]))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Morning gapper prefilter (S&P 500)")
    parser.add_argument("--min-gap", type=float, default=DEFAULT_MIN_GAP_PCT)
    parser.add_argument("--min-price", type=float, default=DEFAULT_MIN_PRICE)
    parser.add_argument("--dry-run", action="store_true", help="don't write watchlist.txt")
    args = parser.parse_args(argv)
    return run(SP500_TICKERS, args.min_gap, args.min_price, args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
