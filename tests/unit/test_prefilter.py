NOW = datetime(2026, 10, 8, 10, 30, tzinfo=ET)


def bars(prev_close, open_, close, high=None, low=None, last_day="2026-10-08"):
    """Two daily bars: yesterday and today."""
    return pd.DataFrame(
        {
            "Open": [prev_close, open_],
            "High": [prev_close, high or max(open_, close)],
            "Low": [prev_close, low or min(open_, close)],
            "Close": [prev_close, close],
        },
        index=pd.to_datetime(["2026-10-07", last_day]),
    )


class TestScreen:
    def test_survivor_carries_the_computed_numbers(self):
        result = screen({"AAPL": bars(180.0, 185.2, 186.3)}, 3.0, 3.0)
        (c,) = result.survivors
        assert c.symbol == "AAPL"
        assert c.gap_pct == pytest.approx(3.5)
        assert (c.open, c.prev_close, c.close) == (185.2, 180.0, 186.3)

    def test_gap_is_measured_from_yesterdays_close_to_todays_close(self):
        # opens flat but runs: gap uses the live close, not the open
        (c,) = screen({"X": bars(100.0, 100.0, 105.0)}, 3.0, 3.0).survivors
        assert c.gap_pct == pytest.approx(5.0)

    def test_below_gap_bucket(self):
        result = screen({"A": bars(100, 100, 101)}, 3.0, 3.0)
        assert result.survivors == [] and result.below_gap == ["A"]

    def test_gap_exactly_at_threshold_survives(self):
        assert len(screen({"A": bars(100, 100, 103)}, 3.0, 3.0).survivors) == 1

    def test_below_price_bucket_wins_over_gap(self):
        result = screen({"P": bars(2.0, 2.0, 2.5)}, 3.0, 3.0)
        assert result.below_price == ["P"] and result.below_gap == []

    def test_price_exactly_at_minimum_survives(self):
        assert len(screen({"A": bars(2.8, 2.8, 3.0)}, 3.0, 3.0).survivors) == 1

    @pytest.mark.parametrize(
        "frame",
        [
            None,
            pd.DataFrame(),
            bars(100, 100, 105).iloc[:1],  # one bar -> IndexError
            bars(100, 100, 105).drop(columns="Close"),  # KeyError
            bars(100, 100, float("nan")),  # NaN -> ValueError
            bars(0.0, 1.0, 5.0),  # zero prior close -> ValueError
        ],
        ids=["none", "empty", "one-bar", "no-close", "nan", "zero-prev"],
    )
    def test_unusable_data_goes_to_failed_without_crashing(self, frame):
        result = screen({"BAD": frame, "OK": bars(100, 100, 110)}, 3.0, 3.0)
        assert result.failed == ["BAD"]
        assert [c.symbol for c in result.survivors] == ["OK"]

    def test_sorted_by_gap_descending(self):
        result = screen(
            {"A": bars(100, 100, 104), "B": bars(100, 100, 120), "C": bars(100, 100, 108)},
            3.0, 3.0,
        )
        assert [c.symbol for c in result.survivors] == ["B", "C", "A"]

    def test_capped_at_max_survivors_keeping_the_biggest(self):
        frames = {f"T{i:02d}": bars(100, 100, 104 + i) for i in range(25)}
        result = screen(frames, 3.0, 3.0)
        assert MAX_SURVIVORS == 20 and len(result.survivors) == 20
        assert result.survivors[0].symbol == "T24"
        assert result.survivors[-1].symbol == "T05"


class TestTripwires:
    @pytest.mark.parametrize(
        "failed, total, expected",
        [
            (0, 503, []),
            (150, 503, []),  # 29.8% -> fine
            (151, 503, ["ALERT: yfinance degradation (failed 151/503)"]),
            (477, 503, ["ALERT: yfinance degradation (failed 477/503)"]),  # 94.8%
            (478, 503, ["ALERT: Yahoo-wide failure suspected; check yfinance changelog"]),
            (503, 503, ["ALERT: Yahoo-wide failure suspected; check yfinance changelog"]),
        ],
    )
    def test_thresholds(self, failed, total, expected):
        assert tripwire_alerts(failed, total) == expected

    def test_zero_total_has_no_alert(self):
        assert tripwire_alerts(0, 0) == []


class TestWatchlistFormat:
    def test_exact_format(self):
        result = screen({"AAPL": bars(180.0, 185.2, 186.3), "BRK B": bars(500, 500, 520)}, 3.0, 3.0)
        text = format_watchlist(result.survivors, 3.0, 3.0, total=503, now=NOW)
        assert text.splitlines() == [
            "# Auto-generated by morning_prefilter.py at 2026-10-08 10:30 EDT",
            "# Filters: gap >= 3.0%, price >= $3.0",
            "# Source: yfinance (screening only); IBKR handles execution",
            "# Survivors: 2 (capped at 20) of 503",
            "#",
            "# ticker  # gap +X.XX%  open $X.XX  prev $X.XX",
            "BRK B  # gap +4.00%  open $500.00  prev $500.00",
            "AAPL  # gap +3.50%  open $185.20  prev $180.00",
        ]

    def test_reader_ignores_comments_and_keeps_order(self, tmp_path):
        result = screen({"AAPL": bars(180.0, 185.2, 186.3), "BRK B": bars(500, 500, 520)}, 3.0, 3.0)
        path = tmp_path / "watchlist.txt"
        path.write_text(format_watchlist(result.survivors, 3.0, 3.0, 503, NOW), encoding="utf-8")
        assert read_watchlist(path) == ["BRK B", "AAPL"]

    def test_no_survivors_still_has_header_and_reads_empty(self, tmp_path):
        path = tmp_path / "watchlist.txt"
        path.write_text(format_watchlist([], 3.0, 3.0, 503, NOW), encoding="utf-8")
        assert "# Survivors: 0 (capped at 20) of 503" in path.read_text()
        assert read_watchlist(path) == []


class Harness:
    def __init__(self, tmp_path, frames=None, error=None):
        self.path = tmp_path / "watchlist.txt"
        self.out, self.err = [], []
        self.frames, self.error = frames, error
        self.downloaded = []
        self.sent = []  # (title, body, priority)
        self.notifier_error = None

    def notify(self, title, body, priority="default"):
        if self.notifier_error:
            raise self.notifier_error
        self.sent.append((title, body, priority))

    def download(self, symbols):
        self.downloaded.append(list(symbols))
        if self.error:
            raise self.error
        return self.frames

    def run(self, symbols, dry_run=False, min_gap=3.0, min_price=3.0):
        code = run(
            symbols, min_gap, min_price, dry_run, self.download,
            now=NOW, watchlist_path=self.path, out=self.out.append, err=self.err.append,
            notify=self.notify,
        )
        return code, (json.loads(self.out[-1]) if self.out else None)


class TestRun:
    def frames(self):
        return {
            "UP": bars(100, 100, 110),
            "FLAT": bars(100, 100, 100.5),
            "PENNY": bars(2.0, 2.0, 2.5),
            "BAD": None,
        }

    def test_summary_json_keys_and_counts(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        code, summary = h.run(["UP", "FLAT", "PENNY", "BAD"])
        assert code == 0
        assert set(summary) == {
            "success", "total_screened", "survivors_count", "below_gap",
            "below_price", "failed", "elapsed_seconds", "top_20_survivors",
            "watchlist_path",
        }
        assert summary["success"] is True and summary["total_screened"] == 4
        assert (summary["survivors_count"], summary["below_gap"]) == (1, 1)
        assert (summary["below_price"], summary["failed"]) == (1, 1)
        assert summary["top_20_survivors"] == ["UP (+10.00%)"]
        assert summary["watchlist_path"] == str(h.path)

    def test_writes_watchlist(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        h.run(["UP", "FLAT", "PENNY", "BAD"])
        assert read_watchlist(h.path) == ["UP"]

    def test_dry_run_does_not_write(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        code, summary = h.run(["UP", "FLAT", "PENNY", "BAD"], dry_run=True)
        assert code == 0 and not h.path.exists()
        assert summary["top_20_survivors"] == ["UP (+10.00%)"]

    def test_thresholds_come_from_arguments(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        _, summary = h.run(["UP", "FLAT", "PENNY", "BAD"], min_gap=0.4, dry_run=True)
        assert summary["top_20_survivors"] == ["UP (+10.00%)", "FLAT (+0.50%)"]

    def test_empty_download_prints_error_json_and_exits_1(self, tmp_path):
        h = Harness(tmp_path, error=PrefilterError("yf.download returned no data"))
        code, summary = h.run(["UP"])
        assert code == 1 and summary["success"] is False
        assert "no data" in summary["error"] and not h.path.exists()

    def test_failed_run_keeps_previous_watchlist(self, tmp_path):
        h = Harness(tmp_path, error=PrefilterError("no data"))
        h.path.write_text("KEEP\n", encoding="utf-8")
        h.run(["UP"])
        assert read_watchlist(h.path) == ["KEEP"]

    def test_degradation_alert_goes_to_stderr_not_stdout(self, tmp_path):
        frames = {f"T{i}": None for i in range(8)} | {"OK": bars(100, 100, 110), "OK2": bars(100, 100, 111)}
        h = Harness(tmp_path, frames)
        code, _ = h.run(list(frames), dry_run=True)
        assert code == 0
        assert h.err == ["ALERT: yfinance degradation (failed 8/10)"]

    def test_success_notification_lists_survivors_with_gap(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        h.run(["UP", "FLAT", "PENNY", "BAD"])
        ((title, body, priority),) = h.sent
        assert title == "Prefilter 10:30 ET" and priority == "default"
        first, *bullets = body.splitlines()
        assert first.startswith("1/4 survivors in ") and first.endswith("s")
        assert bullets == ["• UP +10.00%"]

    def test_success_notification_lists_at_most_the_top_20(self, tmp_path):
        frames = {f"T{i:02d}": bars(100, 100, 104 + i) for i in range(25)}
        h = Harness(tmp_path, frames)
        h.run(list(frames))
        assert len(h.sent[0][1].splitlines()) == 1 + 20

    def test_no_notification_on_dry_run(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        h.run(["UP", "FLAT", "PENNY", "BAD"], dry_run=True)
        assert h.sent == []

    def test_failure_notification_is_high_priority(self, tmp_path):
        h = Harness(tmp_path, error=PrefilterError("yf.download returned no data"))
        h.run(["UP"])
        assert h.sent == [("Prefilter FAILED 10:30 ET", "yf.download returned no data", "high")]

    def test_failure_on_dry_run_is_not_notified(self, tmp_path):
        h = Harness(tmp_path, error=PrefilterError("no data"))
        h.run(["UP"], dry_run=True)
        assert h.sent == []

    def test_degradation_tripwire_sends_a_high_priority_alert(self, tmp_path):
        frames = {f"T{i}": None for i in range(8)} | {"OK": bars(100, 100, 110), "OK2": bars(100, 100, 111)}
        h = Harness(tmp_path, frames)
        h.run(list(frames))
        alerts = [s for s in h.sent if s[2] == "high"]
        assert alerts == [("Prefilter ALERT 10:30 ET", "ALERT: yfinance degradation (failed 8/10)", "high")]
        assert any(s[2] == "default" for s in h.sent)  # the normal summary still goes out

    def test_a_failing_notifier_does_not_break_the_run(self, tmp_path):
        h = Harness(tmp_path, self.frames())
        h.notifier_error = RuntimeError("telegram is down")
        code, summary = h.run(["UP", "FLAT", "PENNY", "BAD"])
        assert code == 0 and summary["success"] is True
        assert read_watchlist(h.path) == ["UP"]

    def test_warns_when_latest_bar_is_not_today(self, tmp_path):
        frames = {"OLD": bars(100, 100, 110, last_day="2026-10-07")}
        h = Harness(tmp_path, frames)
        h.run(["OLD"], dry_run=True)
        assert any("not today" in line for line in h.err)
